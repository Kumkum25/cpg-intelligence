"""Minimal, real PDF export for the executive summary report (Reports page).
Deliberately simple — a clean one-page brief, not a pixel copy of the
on-screen dashboard.
"""
from __future__ import annotations

from fpdf import FPDF

_UNICODE_TO_ASCII = {
    "—": "-", "–": "-", "‘": "'", "’": "'",
    "“": '"', "”": '"', "…": "...", "•": "-",
}


def _ascii_safe(text: str) -> str:
    """The core Helvetica font only supports latin-1; swap common unicode
    punctuation for ASCII equivalents and drop anything else that doesn't
    fit, rather than crashing the export.
    """
    for uni, ascii_eq in _UNICODE_TO_ASCII.items():
        text = text.replace(uni, ascii_eq)
    return text.encode("latin-1", errors="replace").decode("latin-1")


def build_executive_summary_pdf(overview: dict, summary_text: str) -> bytes:
    pdf = FPDF(format="A4")
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.add_page()

    pdf.set_font("Helvetica", "B", 18)
    pdf.cell(0, 10, "Nexus CPG Intelligence", ln=True)
    pdf.set_font("Helvetica", "", 11)
    pdf.set_text_color(90, 90, 90)
    pdf.cell(0, 7, _ascii_safe(f"Executive Summary - as of {overview.get('asof', '')}"), ln=True)
    pdf.set_text_color(0, 0, 0)
    pdf.ln(4)

    pdf.set_font("Helvetica", "B", 13)
    pdf.cell(0, 8, "Key Metrics", ln=True)
    pdf.set_font("Helvetica", "", 11)
    rows = [
        ("Total SKUs", overview.get("total_skus")),
        ("Total Stores", overview.get("total_stores")),
        ("Demand Series (SKU x Store)", overview.get("total_series")),
        ("Lifetime Units Sold", f"{overview.get('total_units_sold_lifetime', 0):,.0f}"),
        ("Estimated Daily Gross Profit", f"${overview.get('total_estimated_daily_gross_profit', 0):,.2f}"),
        ("Declining-Trend SKUs", overview.get("declining_sku_count")),
        ("Regime-Shift Alerts", overview.get("regime_shift_count")),
        ("Stockout-Exposed SKUs", overview.get("stockout_exposed_count")),
        ("High MOQ-Risk Supplier Lines", overview.get("high_moq_risk_count")),
        ("Surplus-Risk Supplier Lines", overview.get("surplus_risk_count")),
        ("Series Missing Financial Data", overview.get("missing_financial_data_count")),
    ]
    for label, value in rows:
        pdf.cell(95, 7, str(label), border=0)
        pdf.cell(0, 7, str(value), ln=True)

    pdf.ln(4)
    pdf.set_font("Helvetica", "B", 13)
    pdf.cell(0, 8, "Demand Classification Mix (90D)", ln=True)
    pdf.set_font("Helvetica", "", 11)
    for cls, count in (overview.get("demand_class_counts_90d") or {}).items():
        pdf.cell(95, 7, cls, border=0)
        pdf.cell(0, 7, str(count), ln=True)

    pdf.ln(4)
    pdf.set_font("Helvetica", "B", 13)
    pdf.cell(0, 8, "AI-Generated Risk Narrative", ln=True)
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(60, 60, 60)
    pdf.multi_cell(0, 6, _ascii_safe(summary_text or "No summary generated."))

    pdf.ln(8)
    pdf.set_font("Helvetica", "I", 8)
    pdf.set_text_color(140, 140, 140)
    pdf.multi_cell(0, 5, "Generated by Nexus CPG Intelligence. All figures are computed by nexus_engine, not estimated by the AI assistant.")

    return bytes(pdf.output())
